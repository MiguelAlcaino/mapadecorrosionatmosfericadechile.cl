<h1 class="titulo">OBJETIVOS DEL PROYECTO</h1>

<h2 class="subtitulo">Objetivo General del Proyecto.</h2>
Construir mapas de índice de agresividad atmosférica y de corrosividad atmosférica, basado en la agresividad ambiental, para los metales o aleaciones que, en su conjunto, constituyen los de mayor interés tecnológico: acero, cobre, aluminio y acero galvanizado, con el fin de seleccionar de manera óptima los materiales a utilizar en estructuras metálicas en diferentes zonas ambientales del país.

<h2 class="subtitulo">Objetivos Específicos</h2>
<ul>
<li>Clasificar el territorio nacional en distintas zonas geográficas en base a la agresividad atmosférica (norma ISO 9223), considerando la información meteorológica existente (temperatura, humedad relativa, tiempo de humidificación) y la medición de contaminantes atmosféricos (c1oruro y dióxido de azufre), como también, de la cantidad de lluvia caída, velocidad del viento y radiación solar.</li>
<li>Identificar el efecto de la corrosión en el comportamiento mecánico de los materiales, evaluado a través de su tenacidad.</li>
<li>Proponer modelos que relacionen la velocidad de corrosión de los diferentes metales y aleaciones bajo estudio, con las variables meteorológicas y de contaminación.</li>
<li>Construir mapas de corrosividad atmosférica para cada metal y aleación en estudio, en base a la velocidad de corrosión obtenida en las estaciones de ensayo seleccionadas según índice de agresividad (norma ISO 9226).</li>
<li>Proponer las bases para especificaciones técnicas en el control y prevención de la corrosión atmosférica.</li>
</ul>
